// Helper to create staged badges with all official level tiers
function makeStaged(name, levels) {
  return levels.map(lvl => ({
    id: "st_" + name.toLowerCase().replace(/[^a-z0-9]/g, "_") + "_lvl" + lvl,
    name: name + " - Level " + lvl,
    cat: "staged"
  }));
}

